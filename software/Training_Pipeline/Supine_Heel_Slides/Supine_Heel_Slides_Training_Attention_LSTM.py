def match_labels(x_sequences, sequence_keys, metadata_labels, y):
  #x_sequences are the actual input sequences
  #sequence_keys are (video_id, patient_id, rep_id) that belong to each sequence

  #create a label look up dictionary where the keys would be added using the metadata of the labels
  label_lookup={}

  #create an empty list to store only the label list in the exact order as of sequences
  y_sequences=[]

  #to store the sequence mapping verification information for each sequence
  #in this, later things such as sequence_index, sequence_key (video_id, rep_id), number of frames in that sequence, label for that sequence
  sequence_mapping_table=[]

  #to add the keys to this look up dictionary, loop through the metadata labels column
  for idx, row in metadata_labels.iterrows():
    #where idx is the index of the rows and row is the (video_id, patient_id, rep_id) of the entire row
    #now construct the composite key
    key= (row["video_id"], row["rep_id"])
    #.loc[idx] takes the list of labels (correct, heel_lift, velocity) for that particular row
    #.to_numpy() then converts it to a numpy list
    label= y.loc[idx].to_numpy()
    #now put the key and label together
    label_lookup[key]= label
    #after the loop ends, label_lookup contains the label of every rep_id in the split

  #loop over the dictionary to extract only the values (labels) from the key value pair
  for sequence_index, key in enumerate(sequence_keys):
    #till now, label lookup has the labels stored in the order of what is stored in label csv. in order to match the order of x_sequences
    label= label_lookup[key]
    y_sequences.append(label)
    #this matches the feature sequences and label sequences in the same order

    #store the sequence to label mapping information
    sequence_mapping_table.append({
      "sequence_index": sequence_index,
      "video_id": key[0],
      "rep_id": key[1],
      "sequence_length": len(x_sequences[sequence_index]),
      "heel_lift": label[0],
      "velocity": label[1]
    })
  #convert the sequence mapping into a table
  sequence_mapping_df= pd.DataFrame(sequence_mapping_table)

  return x_sequences, y_sequences, sequence_mapping_df

"""STEP 7: CHECK CLASS DISTRIBUTION"""

def class_distribution(y_sequences, label_columns):
  y_train_array= np.array(y_sequences)
  #we have to count how many rep_ids are positive for each label
  positive_counts= y_train_array.sum(axis=0) #axis=0 sums over each column
  #make it into a dictionary that has the label name and count for reps for that label
  distribution= dict(zip(label_columns, positive_counts))

  return distribution

"""STEP 8: HANDLE CLASS IMBALANCE"""

def handle_class_imbalance(y_sequences, label_columns):
  distribution= class_distribution(y_sequences, label_columns)

  #dictionary to store the class weights
  class_weights= {}
  #in order to assign weights, we also need the negative counts
  for label, positive_counts in distribution.items():
    negative_counts= len(y_sequences)- positive_counts

    #this is inverse frequency weighting
    #we need both, the positive and negative weights
    #this is done to stop the majority classes from dominating the loss during training
    #total contribution of both classes (positive and negative) to the loss should be roughly the same
    positive_weights= len(y_sequences)/(2*positive_counts)
    negative_weights= len(y_sequences)/(2*negative_counts)

    #save these class weights for the particular label
    class_weights[label]= {
        "positive_weight": positive_weights,
        "negative_weight": negative_weights
      }

  return class_weights

"""STEP 9: SORT THE SEQUENCES AND PADDING

"""

#since the time series sequences that are fed to the model are of variable length
#perform length bucketing + masking
#sequences of similar lengths get placed in the same bucket (batch)
#this is done to prevent one single sequence of a long length to unnecessarily cause a lot of padding
#so we group sequences with similar lengths before batching
#the masking layer tells the LSTM that 0 timestamps are padding and ignore those rather than learning from those

def sort_sequences_and_pad(x_sequences, y_sequences, sequence_mapping_df):
  #first get the lengths of each sequence
  sequence_lengths= sequence_mapping_df["sequence_length"].to_numpy() #convert the pandas series to numpy
  #find the indices that would sort the sequence lengths in ascending order
  #argsort returns an array of indices that represents the positions of elements if the original array were sorted
  sequence_indices= np.argsort(sequence_lengths)

  #to store the sequence and labels of each batch
  x_batches= []
  y_batches= []

  #reorder the sequences in this order
  x_ordered= [x_sequences[i] for i in sequence_indices]
  y_ordered= [y_sequences[i] for i in sequence_indices]

  #synchronise sequence mapping table with the new sorted order
  sequence_mapping_ordered= sequence_mapping_df.iloc[sequence_indices]
  #reset the index after reordering
  sequence_mapping_ordered= sequence_mapping_ordered.reset_index(drop=True)

  #group the sequences into batches. this gives the batch boundaries
  for i in range(0, len(x_ordered), BATCH_SIZE):
    x_batch= x_ordered[i:i+BATCH_SIZE]
    y_batch= y_ordered[i:i+BATCH_SIZE]
    #to check that sequence mapping hasnt been affected
    sequence_mapping_batch= sequence_mapping_ordered.iloc[i:i+BATCH_SIZE]

    #find the length of the longest sequence in this batch
    max_length= max([len(seq) for seq in x_batch])
    print("Maximum sequence in this batch" + str(max_length))

    #pad each sequence in the current batch
    #oad using a random value (that wont occur otherwise in the dataset)
    #since zero- which is default can occur in the dataset, padded using 2000 which is not likely to occur in the dataset
    x_batch_padded= tf.keras.utils.pad_sequences(x_batch, maxlen= max_length, padding= "post", dtype="float32", value= 2000.0)
    x_batches.append(x_batch_padded)
    y_batches.append(y_batch)

  #to verify that this hasnt changed sequence matching and padding has worked
  for i in range(len(y_batches[0])):
    print(
        sequence_mapping_ordered.iloc[i]["sequence_index"],
        len(x_batches[0][i]),
        sequence_mapping_ordered.iloc[i]["sequence_length"],
        y_batches[0][i],
        sequence_mapping_ordered.iloc[i][["heel_lift", "velocity"]].to_numpy(),
    )

  return x_batches, y_batches

"""STEP 10: BUILD THE WEIGHTED LOSS FUNCTION"""

#since this is multilabel classification, the loss function would be binary crossentropy
#for every label, the true output and models predicited output is compared
#for this, weighted loss needs to be built so that deviation in rarer classes are penalized more
def build_loss_function(class_weights, label_columns):

  #get the positive and negative weight of each class.
  #this would be an array of number of labels (2 in this case)
  #this is now a weighted tensor, gives each label its own weight
  pos_w= np.array([class_weights[label]["positive_weight"] for label in label_columns], dtype= np.float32)
  neg_w= np.array([class_weights[label]["negative_weight"] for label in label_columns], dtype= np.float32)

  #to apply custom weights, we need the per sample, per label loss
  #doing reduction=none would give just the per sample loss and not per label loss
  #thus we cant do keras.losses.BinaryCrossentropy()
  #so we need keras.backend.binary_crossentropy- it returns the shape (batch, label_columns)
  #build the actual function that calculates loss and would be given to the model
  #this receives the true and predicted output
  def weighted_bce(y_true, y_pred):
    #first convert the actual output float
    y_true= tf.cast(y_true, tf.float32)
    #clip the predicted probablity between 0 and 1 strictly
    y_pred= tf.clip_by_value(y_pred, 1e-7, 1-1e-7) #in order to avoid log 0, give a minimum number at the lower end

    #the function that calculates loss
    #when y_true=1, it uses the postive weight and the first part of the equation is used
    #when y_true=0 it uses negative weight and the second part of the equation is used
    loss= -(pos_w*y_true*tf.math.log(y_pred) + neg_w*(1-y_true)*tf.math.log(1-y_pred))

    #then return the loss after averging over all samples in the batch and all labels
    return tf.reduce_mean(loss)
  #return the built loss function
  return weighted_bce

"""STEP 11: BUILD THE ATTENTION LAYER  LSTM MODEL"""

#since keras doesnt provide this layer- create custom layer
#creates a new kind of keras layer using the functionality provided by keras's base Layer class
#this layer inherits the functionalities of this base layer
class AdditiveAttentionPooling(tf.keras.layers.Layer):
  #define the constructor. **kwargs allow keras configuration elements like name and dtype to be passed through
  def __init__(self, **kwargs):
    #initialize the parent keras.layers.Layer functionality that the custom layer relies on
    #super() lets the the custom class inherit and access methods from parent class
    #AdditiveAttentionPooling is the child class and tf.keras.layers.Layer is the parent class
    super().__init__(**kwargs)
    #lstm outputs a 64 dim vector. attention mechanism transforms each 64 dim vector into a 32 dim representation before calculating the attention score
    #or can be kept as 64 only
    #controls the size of the intermediate attention representation. it is a hyperparamter that needs to be tuned
    #choosing the dimensionality of the intermediate representation used to decide how much each timestep matters
    self.attention_unit=64
    self.supports_masking= True

  #next define the trainable parameters that the attention scoring function will use.
  #the scoring function has three trainable parameters- the weight, bias and v (that converts the transformed representation into one scalar score per timestep)
  #create the method that would be called to create the layers trainable parameters
  def build(self, input_shape):
    #input_shape tells the layer the shape of the data it will receive that is (batch, time, hidden vector)
    #extract the dimension of the last element of the lstm output- that is, the size of the hidden vector
    input_dims= input_shape[-1]
    #this is needed since the attention layer needs to create a trainable weight matrix W that transforms each 64 dimensional LSTM output into a smaller attention representation

    #create the weight matrix
    #self.add_weight is a method provided by keras.Layer.layers that creates a trainable parameter that keras tracks and updates during training
    self.W= self.add_weight(
        name= "attention_weight",
        shape= (input_dims, self.attention_unit),
        #to set the initial values before training
        initializer= "glorot_uniform",
        trainable= True
    )

    #now define the bias vector that would be used in the attention scoring
    self.b= self.add_weight(
        name= "attention_bias",
        shape= (self.attention_unit,),
        initializer= "zeros",
        trainable= True
    )

    #define v- the vector which converts the resulting 32 dimensional representation into one attention score per timestep
    self.v= self.add_weight(
        name= "attention_v",
        shape= (self.attention_unit,),
        initializer= "glorot_uniform",
        trainable= True
    )
    #W has 64x32= 2048, b has 32 and v has 32 so total 2112 trainable paramters in the attention scoring mechanism

  #define the call method where the attention layer actually performs the calculations on LSTM outputs
  #build creates the trainable parameters. call() defines how those parameters are used to calculate attention
  def call(self, inputs, mask=None):
    #inputs are the inputs to this layer- that is, the output of LSTM layer
    x= tf.matmul(inputs, self.W) + self.b
    #the resulting x has the shape (batch, time, 32)
    #now apply tanh activation to the result- the non linear activation function that maps to (-1,1)
    x= tf.tanh(x)
    #this is the attention score given to each timestep
    scores= tf.matmul(x, self.v[:, tf.newaxis]) #tf.newaxis expands the dimension of v
    #scores has the shape (batch, time, 1)
    #remove the last dimension from scores. should be (batch, time)
    scores= tf.squeeze(scores, axis=-1)
    #since return sequences are true, LSTM would output at every time step, even the masked timestep
    if mask is not None:
      #tf.where does (condition, value if true, value if false)
      #the keras Masking layer gives false if timestamp is padded and true if not
      scores= tf.where(mask, scores, tf.constant(-1e9, dtype=scores.dtype))
      #this makes the scores of the padded timesteps to a very large negative number
      #so when softmax is applied, this negative score receives effectively zero attention weight

    #apply softmax to convert the scores to attention weights
    attention_weights= tf.nn.softmax(scores, axis=1) #axis=0 is batch, axis=1 is time
    #each attention score is between 0 and 1. the sum of weights for one sequence is 1. padded timesteps receive 0 weight

    #weighted sum of all lstm outputs to get the summary vector
    context_vector= tf.reduce_sum(inputs*attention_weights[:,:,tf.newaxis], axis=1)#this has the shape (batch, 64)

    return context_vector

  #to tell that no mask should be passed to the next layer
  def compute_mask(self, inputs, mask= None):
    return None

def build_attention_lstm_model(num_features, num_labels, dropout_rate):
  model= keras.Sequential([
      #input layer- the features
      #its shape is None, num_features. num_features is the number of features
      #since the number of individual time series values (frames) in each batch varies (as the maximum sequence length of a batch is the local maximum)
      #global maximum is not taken for padding so there is no fixed max_len known. so, since the sequence length varies over batches, it is None
      keras.Input(shape=(None, num_features)),
      #the masking layer that asks the model to ignore the padded values. since the padding value was gives as 2000, it should match here as well
      keras.layers.Masking(mask_value=2000),
      #the first LSTM layer that takes in the masked inputs and outputs a vector of size "units", which is the feature extractor
      #reads the raw input and produces a hidden state which contains the features it has extracted for the time series sequence
      #64 is unit size or hidden state memory. it gets 64 slots that the network can use to track something. every slot is updated at every timestep
      #stateful is False so hidden and cell state are reset from one batch sample to another
      #since this is an attention based LSTM, this returns the output at each frame- so return sequences is True
      #it gives back the state at every frame of shape (batch, time, 64)
      keras.layers.LSTM(64, activation= 'tanh', recurrent_activation= 'sigmoid', stateful=False, return_sequences= True),
      #after this lstm layer, add the additive attention. this additive attention receives the LSTM output at every step
      #add the custom additive attention pooling layer
      AdditiveAttentionPooling(),
      #dropout is needed in order to prevent overfitting
      #during training only, the network randomly switches off a fraction of the values of the output (not the weight and bias- the output)
      keras.layers.Dropout(dropout_rate),
      #the dense layer that helps in the final classification. it outputs the probabilities that are then used to predict the class of each label
      #the features extracted from the raw time series (using LSTM) are used to classify
      #since this is multi label classification (prob of each label is needed), the sigmoid activation function is used
      keras.layers.Dense(num_labels, activation= 'sigmoid')
  ])

  #get the summary of the model
  model.summary()

  return model

