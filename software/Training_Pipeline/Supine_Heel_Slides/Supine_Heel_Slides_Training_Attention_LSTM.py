def define_callbacks():

  callbacks=[
      #early stopping- stop training when validation performance stops imporving so it doesnt train to overfitting
      #stops training when the monitored metric has stopped improving. waits for 15 epochs (since patience is 15)
      keras.callbacks.EarlyStopping(
          monitor= "val_loss",
          patience= 15,
          #the smallest change that counts as an improvement. if it is 0, any change counts as an improvement
          min_delta= 0,
          #if set true, weights from the best epoch are restored and that is saved. if set to false, weights from the latest epoch are saved
          restore_best_weights= True,
          #to print the message when it stops. if set to 0 no message is print
          verbose=1
      ),

      #reduce learning rate on plateau- that is, when validation stalls
      keras.callbacks.ReduceLROnPlateau(
          monitor= "val_loss", #what parameter to monitor
          factor= 0.5,  #the multiplier applied to the old lr. so in this case, the new lr is half the old lr
          patience= 7, #how many epochs to wait for before reducing learning rate
          min_lr= 1e-7,
          verbose=1
      ),

      #save the model on checkpoints
      keras.callbacks.ModelCheckpoint(
          filepath= "best_model.keras",
          monitor= "val_loss",
          save_best_only= True,
          verbose=1
      )
  ]
  return callbacks

#since padding has been done at local level, all batches, while being fed at to the model cannot be stacked in a single np array (as they are of variable sequences)
#thus we need a generator function that feeds batches by yielding one batch at a time
#accepts the batched padded sequences as input
#shuffle randomizes the order in which batches are yield for each epoch
def batch_generator(x_batches, y_batches, shuffle= False):
  #np.arange() is generally used to generate a sequence of numbers at regular intervals and returns a np array
  #its general arguments are (start, stop, step) where start and step are optional
  #this gives the index of every batch that generator needs to feed to the model
  batch_indices= np.arange(len(x_batches))
  #these indices can then be used like
  # batch_index | input batch | corresponding label batch
  #      0      | x_batches[0]| y_batches[0]

  #if the batches are to be shuffled for every epoch, the indices are to be randomized
  #although this shuffles the indices, it shuffles only once and not at the beginning of every epoch
  if shuffle:
    np.random.shuffle(batch_indices)

  #for every index, take the corresponding batch of features and labels and yeild them
  #unlike return that exits a function completely and destroys the local variables
  #yield turn that function into a generator function
  #it pauses the function, saves it state and allows the function to produce multiple values over time
  for i in batch_indices:
    yield x_batches[i], np.asarray(y_batches[i], dtype=np.float32) #yield label as an array

