#to build the inference for all repetitions
def infer_test_repetitions(model, x_test_seq, y_test_seq, sequence_mapping_df, label_columns, threshold):
  #to store the predicted probabilities of both classes for every test rep
  pred_prob=[]
  pred_labels=[]

  #create the table that would store the results
  results= sequence_mapping_df[["video_id", "rep_id"]].copy()
  #add the actual labels to the results table
  results["actual_heel_lift"]= sequence_mapping_df["heel_lift"]
  results["actual_velocity"]= sequence_mapping_df["velocity"]

  #now loop through each sequence in the test set
  for sequence in x_test_seq:
    #currently the sequence has the shape (sequence_length, num_features) but the model also expects a
    #but the model expects the input in three dimensions as it would also consider batch size. so expand the dimensions of the input
    #this adds a new dimension at position 0 representing the batch size
    x_input= np.expand_dims(sequence, axis=0)

    #to infer the probabilities for both classes
    #normal model.predict returns a 2d np array as it returns probablities in batches. for this we need prob of only one sequence so [0]
    prob= model.predict(x_input, verbose=0)[0]
    #prob[0] would give prob of heel lift and prob[1] for velocity
    #add these probabilities to the empty list
    pred_prob.append(prob)
    #make the binary prediction. (prob>=THRESHOLD) creates a boolean array. and astype(int) converts the False, True values into integers
    lab= (prob>=THRESHOLD).astype(int)
    pred_labels.append(lab)

  #convert both the lists into np arrays
  pred_prob= np.array(pred_prob)
  pred_labels= np.array(pred_labels)

  results["prob_heel_lift"]= pred_prob[:, 0]
  results["prob_velocity"]= pred_prob[:, 1]

  results["pred_heel_lift"]= pred_labels[:, 0]
  results["pred_velocity"]= pred_labels[:, 1]

  return results

