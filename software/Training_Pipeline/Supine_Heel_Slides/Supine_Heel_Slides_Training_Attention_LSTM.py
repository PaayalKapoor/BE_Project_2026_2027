def compile_and_train(model, weighted_bce, x_batches_train, y_batches_train, x_batches_val, y_batches_val, callbacks):
  #compile the model- prepare the training configurations.
  #configure the learning process before training begins. fix things like- loss function, optimizer, metrics
  #the type of loss function and metrics depend on the task to be done- which is classification here
  model.compile(
      optimizer= keras.optimizers.Adam(learning_rate= 0.001),
      loss= weighted_bce,
      #metrics are numbers that keras calculates and reports for user while training but has no effect on learning. they dont change metrics but callbacks can watch them
      metrics= [
          keras.metrics.BinaryAccuracy(name= "accuracy"),
          keras.metrics.AUC(name="auc", multi_label=True),
          keras.metrics.AUC(name="pr_auc", curve="PR", multi_label=True),
      ]
    )
  #since everytime a fresh generator iteration needs to be passed, that is for every epoch, there should be a new shuffle of batches
  #one single input has to be passed to the training- cannot pass a list of differently shaped batches
  #create that Dataset
  train_dataset= tf.data.Dataset.from_generator(
      lambda: batch_generator(x_batches_train, y_batches_train, shuffle=True), #the generator
      #output signature defines the shape and data type of the elements yielded by the generator
      #since the generator yields two outputs, thus the output signature would describe two outputs
      output_signature= (
          #to define the shape and dtype of the input batches
          #LSTM input has three dimensions. (batch size, sequence length, features)
          tf.TensorSpec(
            #shape describes the dimensions of the tensor
            #batch size, despite being contant(8) is given as None because the last batch may contain less than 8 samples
            shape= (None, None, x_batches_train[0].shape[-1]),
            #dtype describes the data type of the tensor
            dtype= tf.float32
          ),
          #for the label batches. it has two dimensions- (batch size, number of labels)
          tf.TensorSpec(
            shape=(None, len(y_batches_train[0][0])),
            dtype= tf.float32
          )
      )
  )

  #create the validation dataset
  val_dataset= tf.data.Dataset.from_generator(
      lambda: batch_generator(x_batches_val, y_batches_val, shuffle=False),
      output_signature= (
          #for feature batches
          tf.TensorSpec(
            shape= (None, None, x_batches_val[0].shape[-1]),
            dtype= tf.float32
          ),
          #for label batches
          tf.TensorSpec(
              shape=(None, len(y_batches_val[0][0])),
              dtype= tf.float32
          )
      )
  )

  train_dataset = train_dataset.repeat()

  #training the model
  history= model.fit(
      #since both features and labels are already combined into a single dataset, x and y dont have to be given separately
      #keras recognizes each element as a pair and unpacks it automatically
      #it also automatically receives the batch size from the train_dataset
      #since the data is tf.data.Dataset, batch size should not be specified
      #shuffle argument is ignored when training data is tf.data.Dataset
      train_dataset,
      epochs= EPOCHS,
      callbacks= callbacks,
      validation_data= val_dataset,
      #since it is not known in this setup, how many batches make up one training epoch, this tells keras how many batches to consume before moving to the next epoch
      steps_per_epoch= len(x_batches_train),
      #since it is not known in this setup, how many batches make up one validation epoch,
      validation_steps= len(x_batches_val),
      verbose=1
  )

  return model, history

