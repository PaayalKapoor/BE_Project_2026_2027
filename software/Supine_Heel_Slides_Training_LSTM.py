def handle_class_imbalance(y_sequences, label_columns):
    y_array = np.array(y_sequences)
    total_reps = len(y_sequences)
    class_weights = {}

    for i, label in enumerate(label_columns):
        positive_count = y_array[:, i].sum()
        negative_count = total_reps - positive_count

        # avoid division by zero if a class has no positives
        if positive_count == 0:
            print(f"WARNING: {label} has no positive examples")
            class_weights[label] = {"positive": 1.0, "negative": 1.0}
            continue

        # inverse frequency weighting
        # higher weight for the minority class (positive examples)
        positive_weight = total_reps / (2 * positive_count)
        negative_weight = total_reps / (2 * negative_count)

        class_weights[label] = {
            "positive": positive_weight,
            "negative": negative_weight
        }

        print(f"{label}: positives={int(positive_count)}, "
              f"negatives={int(negative_count)}, "
              f"positive_weight={positive_weight:.3f}, "
              f"negative_weight={negative_weight:.3f}")

    return class_weights

def pad_sequences_custom(x_sequences, y_sequences):
    # find the longest rep in the dataset
    max_len = max(seq.shape[0] for seq in x_sequences)
    num_features = x_sequences[0].shape[1]
    num_labels = len(y_sequences[0])

    # create zero-padded arrays
    x_padded = np.zeros((len(x_sequences), max_len, num_features))
    y_array = np.array(y_sequences)  # shape: (num_reps, num_labels)

    # create mask to track which frames are real vs padded
    # 1 = real frame, 0 = padded frame
    mask = np.zeros((len(x_sequences), max_len))

    for i, seq in enumerate(x_sequences):
        seq_len = seq.shape[0]
        x_padded[i, :seq_len, :] = seq
        mask[i, :seq_len] = 1

    print(f"Padded shape: {x_padded.shape}")
    print(f"Labels shape: {y_array.shape}")
    print(f"Max sequence length: {max_len}")
    print(f"Num features: {num_features}")

    return x_padded, y_array, mask, max_len

def build_lstm_model(num_features, num_labels, max_len, hidden_size=64, dropout_rate=0.3, num_layers=1):
    # input layer
    inputs = keras.Input(shape=(max_len, num_features), name="input")

    # masking layer tells LSTM to ignore padded zero frames
    x = keras.layers.Masking(mask_value=0.0)(inputs)

    # LSTM layers
    # if num_layers > 1, intermediate layers need return_sequences=True
    for i in range(num_layers):
        return_seq = True if i < num_layers - 1 else False
        x = keras.layers.LSTM(
            hidden_size,
            return_sequences=return_seq,
            name=f"lstm_{i+1}"
        )(x)
        x = keras.layers.Dropout(dropout_rate, name=f"dropout_{i+1}")(x)

    # classification head
    # sigmoid because each label is independent binary decision
    outputs = keras.layers.Dense(
        num_labels,
        activation="sigmoid",
        name="classification_output"
    )(x)

    model = keras.Model(inputs=inputs, outputs=outputs)

    model.summary()
    return model

def build_weighted_loss(class_weights, label_columns, y_array):
    # build a weight tensor of shape (num_labels, 2)
    # index 0 = negative weight, index 1 = positive weight
    pos_weights = np.array([
        class_weights[label]["positive"] for label in label_columns
    ], dtype=np.float32)

    neg_weights = np.array([
        class_weights[label]["negative"] for label in label_columns
    ], dtype=np.float32)

    def weighted_binary_crossentropy(y_true, y_pred):
        import tensorflow as tf
        y_true = tf.cast(y_true, tf.float32)

        # per-sample per-label weight
        # where y_true=1 use positive weight, where y_true=0 use negative weight
        weights = y_true * pos_weights + (1 - y_true) * neg_weights

        # standard binary crossentropy per element
        bce = keras.backend.binary_crossentropy(y_true, y_pred)

        # apply weights
        weighted_bce = bce * weights

        return keras.backend.mean(weighted_bce)

    return weighted_binary_crossentropy

def compile_and_train(model, x_train_pad, y_train_arr,
                      x_val_pad, y_val_arr,
                      weighted_loss_fn,
                      epochs=100, batch_size=32):

    model.compile(
        optimizer=keras.optimizers.Adam(learning_rate=0.001),
        loss=weighted_loss_fn,
        metrics=[
            keras.metrics.BinaryAccuracy(name="accuracy"),
            keras.metrics.AUC(name="auc", multi_label=True)
        ]
    )

    # callbacks
    callbacks = [
        # save best model based on validation loss
        keras.callbacks.ModelCheckpoint(
            filepath="best_model.keras",
            monitor="val_loss",
            save_best_only=True,
            verbose=1
        ),
        # stop training when validation loss stops improving
        keras.callbacks.EarlyStopping(
            monitor="val_loss",
            patience=15,
            restore_best_weights=True,
            verbose=1
        ),
        # reduce learning rate when plateau
        keras.callbacks.ReduceLROnPlateau(
            monitor="val_loss",
            factor=0.5,
            patience=7,
            min_lr=1e-6,
            verbose=1
        )
    ]

    history = model.fit(
        x_train_pad, y_train_arr,
        validation_data=(x_val_pad, y_val_arr),
        epochs=epochs,
        batch_size=batch_size,
        callbacks=callbacks,
        verbose=1
    )

    return model, history

