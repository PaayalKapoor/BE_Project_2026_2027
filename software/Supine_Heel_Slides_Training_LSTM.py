def feature_importance_permutation(model, x_test_pad, y_test_arr,
                                   label_columns, feature_names, n_repeats=5):
    from sklearn.metrics import f1_score

    # baseline performance with all features intact
    y_pred_base = (model.predict(x_test_pad) >= 0.5).astype(int)
    baseline_f1 = f1_score(y_test_arr, y_pred_base, average="macro", zero_division=0)
    print(f"\nBaseline macro F1: {baseline_f1:.4f}")

    importances = {}

    for feat_idx, feat_name in enumerate(feature_names):
        scores = []
        for _ in range(n_repeats):
            # copy the test data
            x_permuted = x_test_pad.copy()
            # shuffle this feature across all reps and all timesteps
            np.random.shuffle(x_permuted[:, :, feat_idx])
            # predict with shuffled feature
            y_pred_perm = (model.predict(x_permuted, verbose=0) >= 0.5).astype(int)
            perm_f1 = f1_score(y_test_arr, y_pred_perm,
                               average="macro", zero_division=0)
            # importance = how much performance drops when this feature is shuffled
            scores.append(baseline_f1 - perm_f1)

        importances[feat_name] = np.mean(scores)

    # sort by importance descending
    importances_sorted = dict(
        sorted(importances.items(), key=lambda x: x[1], reverse=True)
    )

    print("\n" + "="*60)
    print("FEATURE IMPORTANCE (permutation)")
    print("higher = more important")
    print("="*60)
    for feat, imp in importances_sorted.items():
        bar = "█" * max(0, int(imp * 100))
        print(f"  {feat:<40} {imp:+.4f}  {bar}")

    return importances_sorted

