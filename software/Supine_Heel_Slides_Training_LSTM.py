#splitting the dataset into training, testing and validation
#this split should be made patient wise. data of no other patient should be in two different sets to avoid data leakage
def split_dataset(x,y,metadata,metadata_labels):
  #to get a list of all patient names exactly once
  unique_patients= metadata["video_id"].unique()
  #split into train and temporary (test + val)
  train_patients, temp_patients= train_test_split(unique_patients, test_size= 0.3, random_state=42, shuffle=True)
  #random state= 42 keeps the split reproducible. every time this code is run, it gives the same split
  #split the temporary set into test and val
  test_patients, val_patients= train_test_split(temp_patients, test_size=0.5, random_state=42, shuffle=True)
  #this gives 70% training set, 15% test and 15% validation

  #to extract the corresponding rows into training set
  #first create boolean masks for train, test, val using patient_id, which will be passed through all rows to classify them to the corresponding sets
