def encode_features(x_train, x_test, x_val):
  #create the encoder. in case any unknown class is received at the time of deployment, ignore it
  encoder= OneHotEncoder(handle_unknown="ignore", sparse_output=False)
  #next, fit the encoder to only the columns that has categorical data
  #["phase"] gives a 1D series. [["phase"]] gives a 2D dataframe
  encoder.fit(x_train[["phase"]])
  #.fit() is a method that each class implements differently
  #with this OneHotEncoder object, .fit reads the entire column passed and learns the unique categories and stores them inside the encoder object
  #here, after fitting, the encoder object just stores the found categories

  #apply what the encoder learnt and transform the phase column
  #.transform changes the column into a numpy array of dimensions (nxm) where n is the number of rows and m is the number of categories
  #phase_train is not a dataframe anymore
  phase_train= encoder.transform(x_train[["phase"]])
  phase_test= encoder.transform(x_test[["phase"]])
  phase_val= encoder.transform(x_val[["phase"]])

  #now convert the numpy arrays back into dataframes
  #for this, first get the names of the encoded columns
  encoded_columns= encoder.get_feature_names_out(["phase"])
  #then convert the numpy array to dataframe
  phase_train= pd.DataFrame(phase_train, columns= encoded_columns, index= x_train.index)
  phase_test= pd.DataFrame(phase_test, columns= encoded_columns, index= x_test.index)
  phase_val= pd.DataFrame(phase_val, columns= encoded_columns, index= x_val.index)

  #merge both the dataframes. but first remove the original phase columns
  x_train= x_train.drop(columns=["phase"])
  x_test= x_test.drop(columns=["phase"])
  x_val= x_val.drop(columns=["phase"])

  #now merge (concatenate) the two dataframes
  x_train= pd.concat([x_train, phase_train], axis=1) #axis=1 stacks columns
  x_test= pd.concat([x_test, phase_test], axis=1)
  x_val= pd.concat([x_val, phase_val],axis=1)
  #return the processed datasets
  return x_train, x_test, x_val, encoder

"""STEP 4: SCALE THE FEATURES"""

def scale_features(x_train, x_test, x_val):
  #create the scaler object. it transforms each feature/column so that it has mean=0 and std dev=1
  #standardization is better in this case because it is less sensitive to new values outside the values of the training set
  scaler= StandardScaler()
  #the scaler object hasnt learnt anything yet
  #upon doing scaler.fit, the scaler object goes through each column independently
  #then for each column, it computes the mean and then the standard deviation. so after fitting the scaler object contains the mean and std dev of each column
  #scaler.fit only learns and stores the information
  #for this first take only the numerical columns
  numerical_columns= x_train.select_dtypes(include=[np.number]).columns
  #fit only on the training set and not on whole dataset. since fit learns and stores information, if whole dataset is used, the information from test and validation leaks into training data
  #also, the mean and std dev the training and testing dataset is scaled on, should be the same (from x train). if different mean and std dev used for test data then it may be scaled differently than trained
  #for example, if a value 100 is scaled to 0 in train (according to train mean and std dev), the same value could be scaled to 0.5 in test if mean and std dev of test is used separately
  #so, mean and std dev is taken from training set (fit only on the training set) and used to transform training, testing and validation set
  scaler.fit(x_train[numerical_columns])
  #transform the training set
  #.transform does scaled value= (value-mean)/std dev, for every value, taking the mean and std dev of that particular columns
  x_train[numerical_columns]= scaler.transform(x_train[numerical_columns])
  #transform the testing set
  x_test[numerical_columns]= scaler.transform(x_test[numerical_columns])
  #transform the validation set
  x_val[numerical_columns]= scaler.transform(x_val[numerical_columns])

  return x_train, x_test, x_val

"""STEP 5: CREATE SEQUENCES"""

def create_sequences(x_train, metadata_train):

  #to group all frames belonging to the same rep- they need to be grouped on the basis of video_id, patient_id, and rep_id
  #frames where all these are common- grouped together as one sequence- one training sample
  #groupby takes all rows that have the same values in these columns and groups them into one single group
  groups= metadata_train.groupby(["video_id", "rep_id"])
  #each group represents one rep_id in the dataset
  #groups is a pandas DataFrameGroupBy object

  #create a list to store the sequence from each rep_id
  x_sequences=[]
  #create a list to store the key that maps to each sequence
  sequence_keys=[]

  for (video_id, rep_id), group in groups:
    #to get both- the group's identifying values (video_id, patient_id, rep_id) and the rows belonging to that group
    #group.index contains the original row indices of the rows that belong to that particular group
    #(video_id, patient_id, rep_id) is the group key and tells which rep. "group" tells which rows in that group

    #get the indices of all the frames belonging to this rep_id
    group_indices= group.index

    #get feature values of all the frames in this rep
    rep_features= x_train.loc[group_indices]

    #this is a DataFrame now but LSTM expects a numpy array
    rep_features= rep_features.to_numpy()

    #append to the list.
    #x_sequences is a python list where x_sequences[0] corresponds to the numpy array containing all features/frames of rep 1
    x_sequences.append(rep_features)

    #the (video_id, patient_id, rep_id) key maps to which sequence needs to be preserved in order to attach the rep wise labels
    sequence_keys.append((video_id, rep_id))

  return x_sequences, sequence_keys

